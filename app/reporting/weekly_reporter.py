"""
Weekly Performance Audit & Risk Compliance Reporter.
Generates institutional weekly summaries with Win Rate, Profit Factor, Max Drawdown,
Avg R-Multiple, and breakdowns by setup type, session, and asset class.
"""

from datetime import datetime, timezone
from typing import Dict, Any, Optional
import os
import json

from app.learning.journal import TradeJournal


class WeeklyReporter:
    def __init__(self, journal: Optional[TradeJournal] = None):
        self.journal = journal or TradeJournal()

    def generate_report_markdown(self) -> str:
        """Produces GitHub Flavored Markdown audit report."""
        report = self.journal.generate_weekly_report()
        stats = self.journal.analyze_statistical_edge()

        md = []
        md.append("# 🏛️ Weekly Institutional Trading Desk Performance Audit")
        md.append(f"**Audit Period:** {report.get('period', 'Last 7 Days')} | **Generated:** {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}\n")

        md.append("## 📊 Executive Summary")
        md.append(f"- **Total Executed Trades:** {report.get('total_trades', 0)}")
        md.append(f"- **Win Rate:** {report.get('win_rate', 0.0)}%")
        md.append(f"- **Net Realized PnL:** ${report.get('net_profit', 0.0):.2f}")
        md.append(f"- **Average R-Multiple:** {report.get('avg_r', 0.0)}R")
        md.append(f"- **Profit Factor:** {stats.get('profit_factor', 0.0)}")
        md.append(f"- **Maximum Historical Drawdown:** ${stats.get('max_drawdown', 0.0):.2f}\n")

        md.append("## 📈 Performance by Asset")
        by_symbol = report.get("by_symbol", {})
        if by_symbol:
            md.append("| Symbol | Net Realized PnL ($) |")
            md.append("| :--- | :--- |")
            for sym, pnl in by_symbol.items():
                pnl_str = f"+${pnl:.2f}" if pnl >= 0 else f"-${abs(pnl):.2f}"
                md.append(f"| **{sym}** | {pnl_str} |")
        else:
            md.append("*No trades closed during this reporting window.*")
        md.append("")

        md.append("## 🧪 Statistical Edge & Sample Size Audit (N >= 30)")
        validated = stats.get("statistically_validated_setups", [])
        unvalidated = stats.get("unvalidated_setups", [])

        if validated:
            md.append("### ✅ Statistically Proven Edge (Retained)")
            md.append("| Setup Trigger | Sample Size | Win Rate | Avg R | Z-Score |")
            md.append("| :--- | :--- | :--- | :--- | :--- |")
            for s in validated:
                md.append(f"| {s['setup']} | {s['sample_size']} | {s['win_rate']}% | {s['avg_r']}R | {s['z_score']} |")
        else:
            md.append("*No setup has reached the 30-sample threshold with statistical edge yet.*")

        if unvalidated:
            md.append("\n### ⏳ Incubation / Insufficient Sample Setups")
            md.append("| Setup Trigger | Sample Size | Win Rate | Status |")
            md.append("| :--- | :--- | :--- | :--- |")
            for s in unvalidated:
                md.append(f"| {s['setup']} | {s['sample_size']} | {s['win_rate']}% | Under observation (<30 samples) |")

        md.append("\n---\n*Generated by Local Institutional Trading Desk & Self-Learning Journal.*")
        return "\n".join(md)
